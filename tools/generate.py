"""Dev-only generator: builds collection code from the PPDM OpenAPI specs."""

import json
import os
import re
import sys
from pathlib import Path

import yaml

HTTP = {"get", "post", "put", "patch", "delete"}
BASE_RE = re.compile(r"^/api/(v\d+)/([^/{}]+)$")
ITEM_RE = re.compile(r"^/api/(v\d+)/([^/{}]+)/\{[^/{}]+\}$")
SCHEMAS_DIR = Path(__file__).resolve().parent / "schemas"
MODULES_DIR = Path(__file__).resolve().parents[1] / "plugins" / "modules"
OPTION_KEYS = {
    "type",
    "required",
    "choices",
    "default",
    "elements",
    "aliases",
    "description",
    "no_log",
}
BEGIN, END = "# BEGIN GENERATED", "# END GENERATED"
ROUTES_FILE = Path(__file__).resolve().parents[1] / "plugins" / "module_utils" / "_routes.py"


def _resolve(spec, schema):
    while "$ref" in schema:
        node = spec
        for part in schema["$ref"].lstrip("#/").split("/"):
            node = node[part]
        schema = node
    return schema


def _readonly(spec, op):
    schema = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
    if not schema:
        return set()
    schema = _resolve(spec, schema)
    props = dict(schema.get("properties", {}))
    for sub in schema.get("allOf", []):  # shortcut: one allOf level, deepen if a spec needs it
        props.update(_resolve(spec, sub).get("properties", {}))
    return {k for k, v in props.items() if _resolve(spec, v).get("readOnly") or v.get("readOnly")}


def build_routes(openapi_dir):
    found = {}  # slug -> version -> {"base", "item", "methods", "readonly"}
    for path in sorted(Path(openapi_dir).glob("*.json")):
        spec = json.loads(path.read_text())
        for p, ops in spec["paths"].items():
            m = BASE_RE.match(p) or ITEM_RE.match(p)
            if not m:
                continue
            ver, slug = m.groups()
            entry = found.setdefault(slug, {}).setdefault(
                ver, {"base": None, "item": None, "methods": set(), "readonly": set()}
            )
            is_item = ITEM_RE.match(p) is not None
            entry["item" if is_item else "base"] = re.sub(r"\{[^}]+\}", "{id}", p) if is_item else p
            entry["methods"] |= {k.upper() for k in ops if k in HTTP}
            for verb in ("put", "post") if is_item else ():
                if verb in ops:
                    entry["readonly"] |= _readonly(spec, ops[verb])
                    break
    routes = {}
    for slug, versions in found.items():
        # higher version wins, but only versions that expose a collection base
        ver = max(
            (v for v, e in versions.items() if e["base"]),
            key=lambda v: int(v[1:]),
            default=None,
        )
        if ver is None:
            continue
        e = versions[ver]
        routes[slug] = {"version": ver, **e, "readonly": sorted(e["readonly"])}
    return routes


def render_routes(routes):
    out = [
        '"""GENERATED by tools/generate.py routes. Do not edit."""',
        "",
        "ROUTES = {",
    ]
    for slug in sorted(routes):
        r = routes[slug]
        out.append(f"    {slug!r}: {{")
        for k in ("version", "base", "item"):
            out.append(f"        {k!r}: {r[k]!r},")
        out.append(f"        'methods': {sorted(r['methods'])!r},")
        ro = f"        'readonly': {r['readonly']!r},"
        if len(ro) <= 120:
            out.append(ro)
        else:  # one element per line keeps the generated file within pep8 limits
            out += ["        'readonly': ["] + [f"            {x!r}," for x in r["readonly"]] + ["        ],"]
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


NAME_RE = re.compile(r"[a-z][a-z0-9_]*")


def check_name(kind, name, where):
    """Names land in generated Python source (ARGUMENT_SPEC keys): only plain identifiers are allowed."""
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise ValueError(f"{where}: {kind} name {name!r} must match {NAME_RE.pattern}")


def render_module_blocks(schema):
    """Return (DOCUMENTATION yaml text, ARGUMENT_SPEC python source) from one schema."""
    doc_opts, spec = {}, {}
    for name, o in schema.get("options", {}).items():
        check_name("option", name, f"module {schema['module']!r}")
        unknown = set(o) - OPTION_KEYS
        if unknown:  # shortcut: no suboptions yet, add when a module needs them
            raise ValueError(f"module {schema['module']!r} option {name!r}: unsupported key(s) {sorted(unknown)}")
        d = {
            "description": [o["description"]] if isinstance(o["description"], str) else o["description"],
            "type": o["type"],
        }
        s = {"type": o["type"]}
        for k in ("required", "choices", "default", "elements", "aliases"):
            if k in o:
                d[k] = s[k] = o[k]
        if o.get("no_log"):
            s["no_log"] = True
        doc_opts[name], spec[name] = d, s
    doc = {
        "module": schema["module"],
        "short_description": schema["short_description"],
        "description": schema["description"],
        "version_added": "1.0.0",
        "author": ["Frederic Jacquet (@fjacquet)"],
        "extends_documentation_fragment": ["fjacquet.ppdm.ppdm"],
        "options": doc_opts,
    }
    lines = ["ARGUMENT_SPEC = dict("]
    for n, s in spec.items():
        line = f"    {n}=dict({', '.join(f'{k}={v!r}' for k, v in s.items())}),"
        if len(line) <= 120:
            lines.append(line)
            continue
        # long literals (choices): one element per line, keeps the file within pep8 limits
        lines.append(f"    {n}=dict(")
        for k, v in s.items():
            if isinstance(v, list) and len(repr(v)) > 80:
                lines += [f"        {k}=["] + [f"            {x!r}," for x in v] + ["        ],"]
            else:
                lines.append(f"        {k}={v!r},")
        lines.append("    ),")
    lines.append(")")
    return yaml.safe_dump(doc, sort_keys=False, width=100), "\n".join(lines) + "\n"


def render_generated_block(schema):
    doc, spec = render_module_blocks(schema)
    texts = {k: schema[k] if schema[k].endswith("\n") else schema[k] + "\n" for k in ("examples", "return")}
    for label, text in (("DOCUMENTATION", doc), *texts.items()):
        if "'''" in text:
            raise ValueError(
                f"module {schema['module']!r}: {label} text contains a triple quote, which breaks the generated string"
            )
    schema = {**schema, **texts}
    return (
        f"{BEGIN}\n# fmt: off\nDOCUMENTATION = r'''\n{doc}'''\n\nEXAMPLES = r'''\n{schema['examples']}'''\n\n"
        f"RETURN = r'''\n{schema['return']}'''\n\n{spec}# fmt: on\n{END}\n"
    )


def module_skeleton(schema):
    """New module file: header, marker block, minimal main (hand-written part follows END)."""
    return (
        "#!/usr/bin/python\n"
        "# GNU General Public License v3.0+ (see COPYING or https://www.gnu.org/licenses/gpl-3.0.txt)\n\n"
        "from __future__ import annotations\n\n" + render_generated_block(schema) + "\n"
        "from ansible.module_utils.basic import AnsibleModule\n"
        "from ansible_collections.fjacquet.ppdm.plugins.module_utils.ppdm import (\n"
        "    connection_argument_spec,\n)\n\n\n"
        "def main():\n"
        "    module = AnsibleModule(\n"
        "        argument_spec=dict(connection_argument_spec(), **ARGUMENT_SPEC), supports_check_mode=True\n"
        "    )\n"
        "    module.exit_json(changed=False)\n\n\n"
        'if __name__ == "__main__":\n    main()\n'
    )


def update_module_text(text, schema, name="module file"):
    block = render_generated_block(schema)
    a = text.find(BEGIN)
    b = text.find(END, a + len(BEGIN)) if a >= 0 else -1
    if a < 0 or b < 0:
        raise ValueError(f"{name}: missing or misordered '{BEGIN}' / '{END}' markers")
    return text[:a] + block + text[b + len(END) :].removeprefix("\n")


def validate_schema(schema, path):
    """Fail with the file and key named instead of a bare KeyError."""
    for key in ("module", "short_description", "description", "examples", "return"):
        if key not in schema:
            raise ValueError(f"{path}: missing required key {key!r}")
    check_name("module", schema["module"], path)
    if schema["module"] != Path(path).stem:
        raise ValueError(f"{path}: module {schema['module']!r} does not match the file name")
    for name, o in schema.get("options", {}).items():
        check_name("option", name, path)
        for key in ("type", "description"):
            if key not in o:
                raise ValueError(f"{path}: option {name!r} is missing required key {key!r}")


def sync_modules(schemas_dir, modules_dir, check):
    """Rewrite (or, with check, only report) every module whose generated block drifted."""
    drift = []
    for path in sorted(Path(schemas_dir).glob("[!_]*.yml")):  # _*.yml are documentation examples
        schema = yaml.safe_load(path.read_text())
        validate_schema(schema, path.name)
        target = Path(modules_dir) / f"{schema['module']}.py"
        old = target.read_text() if target.exists() else None
        new = module_skeleton(schema) if old is None else update_module_text(old, schema, str(target))
        if new != old:
            drift.append(target)
            if not check:
                target.write_text(new)
    return drift


def main(argv, schemas_dir=SCHEMAS_DIR, modules_dir=MODULES_DIR):
    if argv[:1] == ["routes"]:
        d = os.environ.get("PPDM_OPENAPI_DIR", "docs/openapi")
        ROUTES_FILE.write_text(render_routes(build_routes(Path(d))))
        return 0
    if argv[:1] == ["modules"]:
        check = "--check" in argv
        try:
            drift = sync_modules(schemas_dir, modules_dir, check)
        except ValueError as err:
            print(f"error: {err}", file=sys.stderr)
            return 2
        for p in drift:
            print(f"{'drift' if check else 'updated'}: {p}", file=sys.stderr)
        return 1 if (check and drift) else 0
    print("usage: generate.py routes | modules [--check]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
