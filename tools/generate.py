"""Dev-only generator: builds collection code from the PPDM OpenAPI specs."""

import json
import os
import re
import sys
from pathlib import Path

HTTP = {"get", "post", "put", "patch", "delete"}
BASE_RE = re.compile(r"^/api/(v\d+)/([^/{}]+)$")
ITEM_RE = re.compile(r"^/api/(v\d+)/([^/{}]+)/\{[^/{}]+\}$")
ROUTES_FILE = Path(__file__).resolve().parents[1] / "plugins" / "module_utils" / "_routes.py"


def _resolve(spec, schema):
    while "$ref" in schema:
        node = spec
        for part in schema["$ref"].lstrip("#/").split("/"):
            node = node[part]
        schema = node
    return schema


def _readonly(spec, op):
    schema = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
    if not schema:
        return set()
    schema = _resolve(spec, schema)
    props = dict(schema.get("properties", {}))
    for sub in schema.get("allOf", []):  # shortcut: one allOf level, deepen if a spec needs it
        props.update(_resolve(spec, sub).get("properties", {}))
    return {k for k, v in props.items() if _resolve(spec, v).get("readOnly") or v.get("readOnly")}


def build_routes(openapi_dir):
    found = {}  # slug -> version -> {"base", "item", "methods", "readonly"}
    for path in sorted(Path(openapi_dir).glob("*.json")):
        spec = json.loads(path.read_text())
        for p, ops in spec["paths"].items():
            m = BASE_RE.match(p) or ITEM_RE.match(p)
            if not m:
                continue
            ver, slug = m.groups()
            entry = found.setdefault(slug, {}).setdefault(
                ver, {"base": None, "item": None, "methods": set(), "readonly": set()}
            )
            is_item = ITEM_RE.match(p) is not None
            entry["item" if is_item else "base"] = (
                re.sub(r"\{[^}]+\}", "{id}", p) if is_item else p
            )
            entry["methods"] |= {k.upper() for k in ops if k in HTTP}
            for verb in ("put", "post") if is_item else ():
                if verb in ops:
                    entry["readonly"] |= _readonly(spec, ops[verb])
                    break
    routes = {}
    for slug, versions in found.items():
        # higher version wins, but only versions that expose a collection base
        ver = max((v for v, e in versions.items() if e["base"]), key=lambda v: int(v[1:]), default=None)
        if ver is None:
            continue
        e = versions[ver]
        routes[slug] = {"version": ver, **e, "readonly": sorted(e["readonly"])}
    return routes


def render_routes(routes):
    out = ['"""GENERATED by tools/generate.py routes. Do not edit."""', "", "ROUTES = {"]
    for slug in sorted(routes):
        r = routes[slug]
        out.append(f"    {slug!r}: {{")
        for k in ("version", "base", "item"):
            out.append(f"        {k!r}: {r[k]!r},")
        out.append(f"        'methods': {sorted(r['methods'])!r},")
        out.append(f"        'readonly': {r['readonly']!r},")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv):
    if argv[:1] == ["routes"]:
        d = os.environ.get("PPDM_OPENAPI_DIR", "docs/openapi")
        ROUTES_FILE.write_text(render_routes(build_routes(Path(d))))
        return 0
    print("usage: generate.py routes", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
